#!/usr/bin/env python3
"""Battle Master — original score, rendered offline.

Every piece is built from the Bell Marches motif (D4 F4 E4 A4) in D Dorian
with synthesised instruments: a struck bell (inharmonic partials), bowed
strings (detuned saws, filtered), plucked strings (Karplus-Strong), a reed
(filtered pulse with vibrato), a frame drum and wood taps. Loops wrap their
reverb tail into the start so they repeat without a seam.

  python3 scripts/compose.py [--force]  # writes (only missing files unless --force) art/source/sfx/music_*.mp3 and conch.mp3 (needs ffmpeg)
  npm run assets                         # converts them to public/assets/sfx/*.mp3

No samples or recordings are used: the music is generated by this file.
"""
import os
import numpy as np
from scipy.signal import butter, lfilter, fftconvolve
from scipy.io import wavfile

SR = 44100
OUT = os.path.join(os.path.dirname(__file__), '..', 'art', 'source', 'sfx')
rng = np.random.default_rng(1729)

NOTE = {'C': 0, 'C#': 1, 'D': 2, 'Eb': 3, 'E': 4, 'F': 5, 'F#': 6, 'G': 7, 'Ab': 8, 'A': 9, 'Bb': 10, 'B': 11}
def hz(n: str) -> float:
    name, octv = n[:-1], int(n[-1])
    return 440.0 * 2 ** ((NOTE[name] + 12 * (octv + 1) - 69) / 12)

def lp(x, f, order=2):
    b, a = butter(order, min(f / (SR / 2), 0.99), 'low'); return lfilter(b, a, x)
def hp(x, f, order=2):
    b, a = butter(order, max(f / (SR / 2), 1e-4), 'high'); return lfilter(b, a, x)
def bp(x, lo, hi):
    b, a = butter(2, [lo / (SR / 2), hi / (SR / 2)], 'band'); return lfilter(b, a, x)
def env(n, a, r, sustain=1.0):
    e = np.ones(n) * sustain
    na, nr = max(1, int(a * SR)), max(1, int(r * SR))
    e[:na] = np.linspace(0, sustain, na)
    if nr < n: e[-nr:] *= np.linspace(1, 0, nr)
    return e
def t_(dur): return np.arange(int(dur * SR)) / SR

# ---------------- instruments ----------------
def bell(f, dur=4.0, amp=1.0, bright=1.0):
    t = t_(dur)
    parts = [(0.5, 0.9, 1.2), (1.0, 1.0, 0.9), (1.183, 0.55, 0.7), (1.506, 0.45, 0.55), (2.0, 0.5, 0.45),
             (2.514, 0.25 * bright, 0.32), (2.662, 0.2 * bright, 0.3), (3.011, 0.15 * bright, 0.25), (4.166, 0.08 * bright, 0.18)]
    y = sum(a * np.sin(2 * np.pi * f * r * t + rng.random() * 6) * np.exp(-t / (d * dur * 0.6)) for r, a, d in parts)
    y *= np.minimum(1, t / 0.004)
    return amp * y / 3.2

def strings(f, dur, amp=1.0, attack=0.35, release=0.6, cutoff=2200):
    t = t_(dur)
    vib = 1 + 0.0035 * np.sin(2 * np.pi * 5.2 * t + rng.random() * 6) * np.minimum(1, t / 0.6)
    y = np.zeros_like(t)
    for d in (-0.07, 0.0, 0.065):
        ph = np.cumsum(f * (1 + d / 12) * vib) / SR
        y += 2 * (ph % 1.0) - 1
    y = lp(y / 3, cutoff)
    return amp * y * env(len(t), attack, release)

def pluck(f, dur=1.6, amp=1.0, damp=0.996):
    n = int(dur * SR); p = max(2, int(SR / f))
    buf = rng.uniform(-1, 1, p); out = np.zeros(n)
    for i in range(n):
        out[i] = buf[i % p]
        buf[i % p] = damp * 0.5 * (buf[i % p] + buf[(i + 1) % p])
    return amp * lp(out, 4200) * env(n, 0.002, 0.08)

def reed(f, dur, amp=1.0, attack=0.08, release=0.25):
    t = t_(dur)
    vib = 1 + 0.006 * np.sin(2 * np.pi * 5.6 * t) * np.minimum(1, t / 0.4)
    ph = np.cumsum(f * vib) / SR % 1.0
    y = np.where(ph < 0.32, 1.0, -0.47)
    y = bp(y, f * 0.9, min(f * 7, 9000)) + 0.02 * rng.standard_normal(len(t))
    return amp * 0.7 * y * env(len(t), attack, release)

def frame_drum(amp=1.0, f0=95):
    t = t_(0.9)
    f = f0 * (1 + 0.8 * np.exp(-t / 0.025))
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.22)
    slap = lp(rng.standard_normal(len(t)), 2500) * np.exp(-t / 0.018) * 0.35
    return amp * (body + slap)

def tap(amp=1.0, f=1800):
    t = t_(0.12)
    return amp * bp(rng.standard_normal(len(t)), f * 0.7, f * 1.4) * np.exp(-t / 0.02) * 2.2

def low_drum(amp=1.0):
    t = t_(1.4)
    f = 55 * (1 + 0.6 * np.exp(-t / 0.04))
    return amp * (np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.45) + lp(rng.standard_normal(len(t)), 600) * np.exp(-t / 0.05) * 0.4)

# ---------------- mixing ----------------
class Track:
    def __init__(self, bars, bpm, beats=4):
        self.bpm, self.beat = bpm, 60.0 / bpm
        self.dur = bars * beats * self.beat
        self.L = np.zeros(int((self.dur + 6) * SR)); self.R = np.zeros_like(self.L)
    def add(self, sig, at_beat, pan=0.0, gain=1.0):
        i = int(at_beat * self.beat * SR)
        if i >= len(self.L): return
        s = sig[: len(self.L) - i] * gain
        self.L[i:i + len(s)] += s * np.sqrt(0.5 * (1 - pan)); self.R[i:i + len(s)] += s * np.sqrt(0.5 * (1 + pan))
    def render(self, loop=True, verb=0.28, rt=2.6):
        ir_t = t_(rt)
        out = []
        for ch, seed in ((self.L, 3), (self.R, 4)):
            r = np.random.default_rng(seed)
            ir = r.standard_normal(len(ir_t)) * np.exp(-ir_t / (rt / 6.9)); ir = lp(ir, 5200); ir /= np.sqrt(np.sum(ir ** 2))
            wet = fftconvolve(ch, ir)[: len(ch)]
            out.append(ch + verb * wet)
        L, R = out
        n = int(self.dur * SR)
        if loop:
            # fold everything that rings past the loop point back onto its start
            L = L[:n] + np.pad(L[n:2 * n], (0, max(0, n - len(L[n:2 * n]))))[:n]
            R = R[:n] + np.pad(R[n:2 * n], (0, max(0, n - len(R[n:2 * n]))))[:n]
        else:
            L, R = L[: n + int(4 * SR)], R[: n + int(4 * SR)]
        st = np.stack([L, R], 1)
        st = np.tanh(st / (np.max(np.abs(st)) + 1e-9) * 1.25) * 0.9
        return st

def save(name, st):
    os.makedirs(OUT, exist_ok=True)
    # Pon's Gemini recordings (28 Nov 2026) replaced the synthesised pieces: never overwrite an existing master
    if os.path.exists(os.path.join(OUT, f'{name}.mp3')) and '--force' not in os.sys.argv:
        print(f'  {name}.mp3 exists, kept (use --force to overwrite)'); return
    wav = os.path.join(OUT, f'{name}.wav')
    wavfile.write(wav, SR, (st * 32767).astype(np.int16))
    # keep a compact MP3 master in the repo (npm run assets makes the game copy)
    os.system(f'ffmpeg -loglevel error -y -i "{wav}" -codec:a libmp3lame -q:a 2 "{wav[:-4]}.mp3" && rm "{wav}"')
    print(f'  {name}.mp3  {len(st) / SR:.1f}s')

# D Dorian chords (root, third, fifth): Dm, C, Bb, F, Am, G
CH = {'Dm': ['D3', 'F3', 'A3'], 'C': ['C3', 'E3', 'G3'], 'Bb': ['Bb2', 'D3', 'F3'], 'F': ['F2', 'A2', 'C3'],
      'Am': ['A2', 'C3', 'E3'], 'G': ['G2', 'B2', 'D3'], 'Gm': ['G2', 'Bb2', 'D3']}
MOTIF = [('D4', 1), ('F4', 1), ('E4', 0.5), ('A4', 1.5)]          # the bell call: a question
ANSWER = [('G4', 1), ('F4', 0.5), ('E4', 0.5), ('D4', 2)]         # the answer that comes home

def up(n, k):
    """transpose a note name by octaves"""
    return n[:-1] + str(int(n[-1]) + k)

def title():
    tr = Track(16, 72)
    prog = ['Dm', 'Dm', 'Bb', 'C', 'Dm', 'F', 'Gm', 'Am'] * 2
    for b, c in enumerate(prog):
        for k, n in enumerate(CH[c]):
            tr.add(strings(hz(n), tr.beat * 4.2, 0.42, attack=0.9, release=1.2, cutoff=1400), b * 4, pan=(k - 1) * 0.5)
        tr.add(strings(hz(up(CH[c][0], -1)), tr.beat * 4.2, 0.35, attack=1.0, cutoff=500), b * 4)
    for b in (0, 4, 8, 12):
        at = b * 4
        for n, d in MOTIF:
            tr.add(bell(hz(up(n, -1)), 5, 0.9), at, pan=-0.15); at += d
    for b in (2, 6, 10):
        at = b * 4
        for n, d in ANSWER:
            tr.add(reed(hz(n), tr.beat * d * 0.95, 0.32), at, pan=0.3); at += d
    for b in range(16):
        tr.add(frame_drum(0.25, 80), b * 4)
    return tr.render(verb=0.4, rt=3.4)

def camp():
    tr = Track(16, 76)
    prog = ['Dm', 'C', 'Bb', 'C', 'Dm', 'Am', 'Bb', 'C'] * 2
    arp = [0, 1, 2, 1, 0, 2, 1, 2]
    for b, c in enumerate(prog):
        tones = CH[c] + [up(CH[c][0], 1)]
        for i in range(8):
            n = up(tones[[0, 1, 2, 3, 2, 1, 2, 3][i]], 1)
            tr.add(pluck(hz(n), 1.4, 0.5), b * 4 + i * 0.5, pan=0.25 if i % 2 else -0.25)
        tr.add(strings(hz(up(CH[c][0], -1)), tr.beat * 4.1, 0.3, attack=0.4, cutoff=600), b * 4)
        for q in range(4):
            tr.add(tap(0.18 if q % 2 else 0.28, 1500 if q % 2 else 1100), b * 4 + q, pan=0.4)
        _ = arp
    for b in (3, 11):
        at = b * 4
        for n, d in MOTIF:
            tr.add(pluck(hz(up(n, 1)), 2.0, 0.55, 0.998), at, pan=0.1); at += d
    for b in (7, 15):
        at = b * 4
        for n, d in ANSWER:
            tr.add(reed(hz(n), tr.beat * d * 0.9, 0.22), at, pan=-0.2); at += d
    return tr.render(verb=0.3, rt=2.2)

def briefing():
    tr = Track(12, 66)
    prog = ['Dm', 'Bb', 'Gm', 'Am'] * 3
    for b, c in enumerate(prog):
        for k, n in enumerate(CH[c]):
            tr.add(strings(hz(n), tr.beat * 4.3, 0.4, attack=1.2, release=1.5, cutoff=1200), b * 4, pan=(k - 1) * 0.6)
        tr.add(low_drum(0.6), b * 4)
        tr.add(frame_drum(0.25, 70), b * 4 + 2.5)
    for b in (1, 5, 9):
        at = b * 4
        for n, d in MOTIF:
            tr.add(reed(hz(up(n, -1)), tr.beat * d, 0.35, attack=0.2), at, pan=0.2); at += d
    for b in (0, 8):
        tr.add(bell(hz('D3'), 7, 0.8), b * 4)
    return tr.render(verb=0.38, rt=3.0)

def battle(intense=False):
    bpm = 100 if intense else 88
    tr = Track(16, bpm)
    prog = (['Dm', 'C', 'Bb', 'Am'] * 2 + ['Gm', 'Bb', 'C', 'Dm'] * 2)
    for b, c in enumerate(prog):
        root = CH[c][0]
        # driving string ostinato in eighths
        for i in range(8):
            n = up(root, 1) if i % 4 != 3 else up(CH[c][2], 1)
            tr.add(strings(hz(n), tr.beat * 0.45, 0.34, attack=0.01, release=0.08, cutoff=2600), b * 4 + i * 0.5, pan=-0.35)
        for k, n in enumerate(CH[c][1:]):
            tr.add(strings(hz(up(n, 1)), tr.beat * 4.1, 0.2, attack=0.3, cutoff=1800), b * 4, pan=0.4 * (k * 2 - 1))
        tr.add(strings(hz(up(root, -1)), tr.beat * 4.1, 0.34, attack=0.05, cutoff=420), b * 4)
        # frame drum pattern: 1 . (2&) 3 . 4
        for beat, a in ((0, 0.75), (1.5, 0.45), (2, 0.6), (3, 0.5), (3.5, 0.35)):
            tr.add(frame_drum(a, 92), b * 4 + beat, pan=0.1)
        for q in range(8):
            tr.add(tap(0.12 + (0.08 if q % 2 == 0 else 0)), b * 4 + q * 0.5, pan=0.5)
        if intense:
            tr.add(low_drum(0.8), b * 4)
            tr.add(low_drum(0.5), b * 4 + 2)
            for q in range(16):
                tr.add(tap(0.08, 2600), b * 4 + q * 0.25, pan=-0.5)
    # the motif on the reed over bars 4, 8, 12, 16; brass-like answer when intense
    for b in (3, 7, 11, 15):
        at = b * 4
        for n, d in (MOTIF if b % 8 == 3 else ANSWER):
            tr.add(reed(hz(up(n, 1 if intense else 0)), tr.beat * d * 0.95, 0.38 if intense else 0.3), at, pan=0.2); at += d
    if intense:
        for b in (0, 8):
            tr.add(bell(hz('D3'), 4, 0.6, 1.3), b * 4)
    return tr.render(verb=0.24, rt=2.0)

def victory():
    tr = Track(4, 80)
    at = 0
    for n, d in MOTIF[:3] + [('D5', 3.5)]:   # the question finally resolves to D
        tr.add(bell(hz(n), 6, 0.9, 1.2), at); at += d
    for b, c in enumerate(['Bb', 'C', 'Dm', 'Dm']):
        for k, n in enumerate(CH[c]):
            tr.add(strings(hz(up(n, 1 if b else 0)), tr.beat * (4.2 if b < 3 else 6), 0.38, attack=0.2, release=2.0), b * 4, pan=(k - 1) * 0.5)
    tr.add(low_drum(0.7), 8); tr.add(bell(hz('D3'), 7, 1.0), 12)
    return tr.render(loop=False, verb=0.42, rt=3.5)

def defeat():
    tr = Track(4, 60)
    at = 0
    for n, d in MOTIF[:2] + [('E4', 6)]:      # the call fades on its third note
        tr.add(reed(hz(up(n, -1)), tr.beat * d * (1 if d < 3 else 1.0), 0.4, attack=0.15, release=2.5 if d > 3 else 0.2), at); at += d
    for b, c in enumerate(['Dm', 'Gm', 'Dm']):
        for k, n in enumerate(CH[c]):
            tr.add(strings(hz(up(n, -1 if k == 0 else 0)), tr.beat * 4.5, 0.32, attack=0.8, release=2.2, cutoff=900), b * 4, pan=(k - 1) * 0.5)
    tr.add(low_drum(0.5), 0)
    return tr.render(loop=False, verb=0.45, rt=3.6)

def bell_call():
    """the battle-start signal (replaces Yuddh's conch): two strokes of a great bell"""
    tr = Track(2, 80)
    tr.add(bell(hz('D3'), 5, 1.0, 1.1), 0); tr.add(bell(hz('A3'), 5, 0.6, 1.1), 1.0)
    return tr.render(loop=False, verb=0.35, rt=3.0)[: int(3.2 * SR)]

if __name__ == '__main__':
    save('music_title', title())
    save('music_camp', camp())
    save('music_briefing', briefing())
    save('music_battle_calm', battle(False))
    save('music_battle_intense', battle(True))
    save('music_victory', victory())
    save('music_defeat', defeat())
    save('conch', bell_call())
